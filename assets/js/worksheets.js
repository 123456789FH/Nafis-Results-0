function genericBank(subject, domain) {
  return Array.from({ length: 15 }, (_, index) => {
    const number = index + 1;
    if (number <= 5) return q(`اكتب تعريفًا أو مثالًا صحيحًا يوضح مفهوم «${domain}» في مادة ${subject}.`, 'إجابة صحيحة مرتبطة بالمفهوم وفق المنهج والصف.');
    if (number <= 10) return q(`طبّق مهارة «${domain}» على مثال جديد، ووضح خطواتك.`, 'تقبل الإجابات الصحيحة المكتملة والخطوات المنطقية.');
    if (number <= 12) return q(`فسر خطأ شائعًا محتملًا في «${domain}»، ثم صححه.`, 'تفسير صحيح للخطأ وتصحيح مدعوم.');
    return q(`أجب عن سؤال ختامي يقدمه المعلم/ة لقياس «${domain}».`, 'يحدد المحك وفق السؤال والمنهج المعتمد.');
  });
}

export function worksheetFor(grade, subject, domain) {
  const canonical = canonicalDomainName(domain);
  const gradeBanks = grade === 'g9' ? G9_BANKS : BANKS[grade];
  const bank = gradeBanks?.[subject]?.[canonical]
    || BANKS.g6?.[subject]?.[canonical]
    || BANKS.g3?.[subject]?.[canonical]
    || genericBank(subject, canonical);
  return {
    title: `${subject} — ${canonical}`,
    subject,
    domain: canonical,
    grade,
    questions: bank.map((item, index) => ({ ...item, number: index + 1, type: index < 10 ? 'متدرج' : index < 12 ? 'تفكير' : 'ختامي' })),
    requiresReview: true,
    disclaimer: 'هذه ورقة علاجية مقترحة وليست أسئلة رسمية صادرة من هيئة تقويم التعليم والتدريب. يراجع المعلم/ة ملاءمتها للصف والمنهج قبل التطبيق.'
  };
}

export function worksheetsForAnalysis(data, analysis) {
  return (analysis?.actionUnits || []).map(unit => ({ ...worksheetFor(data?.grade || 'g3', unit.subject, unit.domain), priority: unit }));
}
